#creating a list
students = ['Deepika', 'Haritha', 'Lohitha','Dasaradha','Pushpa','Brahmini','Sravani','Kalyani','Savarni','Swathi','Srilekha']
print(students)
#slicing through a list
#printing the first three items in a list
print("The first three items in a list are: ")
print(students[0:3])
#printing the three elements from the middle of a list
print("The three elements in the middle of a list are:")
print(students[4:7])
#printing thr last three elements in a list
print("The last three elements in a list are:")
#we can print in both ways
print(students[8:])#by not mentioning the second index in a list
print(students[-3:])#by using negative index value