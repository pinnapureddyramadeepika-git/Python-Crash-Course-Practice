#writing an if-elif-else chain to determine a person's stage of life
#writing a value to a variable 
age=18
if age<2:
    print("\n The person is a baby")
elif age<4:
    print("\n The person is a toddler")
elif age<13:
    print("\n The person is a kid")  
elif age<20:
    print("\n The person is a teenager") 
elif age<65:
    print("\n The person is an adult")
else:
    print("\nThe person is an elder")              